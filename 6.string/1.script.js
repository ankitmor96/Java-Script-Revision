let name = "ankit mor";

// charAt :-

console.log(name.charAt(3)); // string

// endsWith :-

console.log(name.endsWith("r")); // Boolean 

// startsWith :-

console.log(name.startsWith("n")); // Boolean

// includes :-

console.log(name.includes("m")); // Boolean

// concat :-

console.log(name.concat(" ", "age is 20")); 

// indexof :-

console.log(name.indexOf("mor"));

//last indexOf :-

console.log(name.lastIndexOf("t"));

// length :-

console.log(name.length);

// match :-

console.log(name.match(""));

// repeat :-

console.log(name.repeat("5"));

// repleace :-

console.log(name.replace("i","I"));

// search :-

console.log(name.search("a"));

// slice :-

console.log(name.slice(2,6));